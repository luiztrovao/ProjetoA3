-- Imagens enviadas pelo sistema (logo da lanchonete e fotos dos produtos), guardadas no próprio banco.
-- Substitui as colunas de URL criadas na V3, que não tinham upload.

CREATE TABLE imagem (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conteudo      BYTEA       NOT NULL,
    tipo_conteudo VARCHAR(30) NOT NULL,
    tamanho       INTEGER     NOT NULL,
    criado_em     TIMESTAMP   NOT NULL,
    CONSTRAINT ck_imagem_tipo CHECK (tipo_conteudo IN ('image/png', 'image/jpeg')),
    CONSTRAINT ck_imagem_tamanho CHECK (tamanho > 0)
);

ALTER TABLE produto ADD COLUMN imagem_id BIGINT;
ALTER TABLE produto ADD CONSTRAINT fk_produto_imagem FOREIGN KEY (imagem_id) REFERENCES imagem (id);
ALTER TABLE produto DROP COLUMN imagem_url;

ALTER TABLE configuracao ADD COLUMN logo_id BIGINT;
ALTER TABLE configuracao ADD CONSTRAINT fk_configuracao_logo FOREIGN KEY (logo_id) REFERENCES imagem (id);
ALTER TABLE configuracao DROP COLUMN logo_url;
