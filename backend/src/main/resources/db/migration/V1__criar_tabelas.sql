-- Estrutura inicial do banco. Documentação: docs/modelagem/modelo-de-dados.md

CREATE TABLE usuario (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome          VARCHAR(120) NOT NULL,
    email         VARCHAR(150) NOT NULL,
    senha_hash    VARCHAR(100) NOT NULL,
    perfil        VARCHAR(20)  NOT NULL,
    ativo         BOOLEAN      NOT NULL DEFAULT TRUE,
    criado_em     TIMESTAMP    NOT NULL,
    atualizado_em TIMESTAMP    NOT NULL,
    CONSTRAINT uk_usuario_email UNIQUE (email),
    CONSTRAINT ck_usuario_perfil CHECK (perfil IN ('DONO', 'GERENTE', 'VENDEDOR'))
);

CREATE TABLE cliente (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome          VARCHAR(120) NOT NULL,
    cpf           VARCHAR(11),
    telefone      VARCHAR(11),
    email         VARCHAR(150),
    ativo         BOOLEAN      NOT NULL DEFAULT TRUE,
    criado_em     TIMESTAMP    NOT NULL,
    atualizado_em TIMESTAMP    NOT NULL,
    CONSTRAINT uk_cliente_cpf UNIQUE (cpf)
);

CREATE TABLE categoria (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome  VARCHAR(60) NOT NULL,
    ativo BOOLEAN     NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_categoria_nome UNIQUE (nome)
);

CREATE TABLE produto (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome           VARCHAR(120)  NOT NULL,
    descricao      VARCHAR(500),
    categoria_id   BIGINT        NOT NULL,
    preco          NUMERIC(10,2) NOT NULL,
    estoque_atual  INTEGER       NOT NULL DEFAULT 0,
    estoque_minimo INTEGER       NOT NULL DEFAULT 0,
    ativo          BOOLEAN       NOT NULL DEFAULT TRUE,
    criado_em      TIMESTAMP     NOT NULL,
    atualizado_em  TIMESTAMP     NOT NULL,
    CONSTRAINT fk_produto_categoria FOREIGN KEY (categoria_id) REFERENCES categoria (id),
    CONSTRAINT ck_produto_preco CHECK (preco > 0),
    CONSTRAINT ck_produto_estoque_atual CHECK (estoque_atual >= 0),
    CONSTRAINT ck_produto_estoque_minimo CHECK (estoque_minimo >= 0)
);

CREATE TABLE venda (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id      BIGINT,
    usuario_id      BIGINT        NOT NULL,
    data_hora       TIMESTAMP     NOT NULL,
    status          VARCHAR(20)   NOT NULL,
    forma_pagamento VARCHAR(20)   NOT NULL,
    subtotal        NUMERIC(10,2) NOT NULL,
    desconto        NUMERIC(10,2) NOT NULL DEFAULT 0,
    total           NUMERIC(10,2) NOT NULL,
    observacao      VARCHAR(500),
    CONSTRAINT fk_venda_cliente FOREIGN KEY (cliente_id) REFERENCES cliente (id),
    CONSTRAINT fk_venda_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id),
    CONSTRAINT ck_venda_status CHECK (status IN ('EM_PREPARO', 'CONCLUIDA', 'CANCELADA')),
    CONSTRAINT ck_venda_forma_pagamento CHECK (forma_pagamento IN ('DINHEIRO', 'PIX', 'CREDITO', 'DEBITO')),
    CONSTRAINT ck_venda_desconto CHECK (desconto >= 0 AND desconto <= subtotal)
);

CREATE TABLE item_venda (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venda_id       BIGINT        NOT NULL,
    produto_id     BIGINT        NOT NULL,
    quantidade     INTEGER       NOT NULL,
    preco_unitario NUMERIC(10,2) NOT NULL,
    subtotal       NUMERIC(10,2) NOT NULL,
    CONSTRAINT fk_item_venda_venda FOREIGN KEY (venda_id) REFERENCES venda (id) ON DELETE CASCADE,
    CONSTRAINT fk_item_venda_produto FOREIGN KEY (produto_id) REFERENCES produto (id),
    CONSTRAINT ck_item_venda_quantidade CHECK (quantidade > 0)
);

-- Índices para as consultas dos dashboards e para as chaves estrangeiras
CREATE INDEX idx_venda_data_hora ON venda (data_hora);
CREATE INDEX idx_venda_status ON venda (status);
CREATE INDEX idx_venda_cliente ON venda (cliente_id);
CREATE INDEX idx_venda_usuario ON venda (usuario_id);
CREATE INDEX idx_item_venda_venda ON item_venda (venda_id);
CREATE INDEX idx_item_venda_produto ON item_venda (produto_id);
CREATE INDEX idx_produto_categoria ON produto (categoria_id);
